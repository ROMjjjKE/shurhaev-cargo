import puppeteer from 'puppeteer-core';
const URL = 'https://romjjjke.github.io/shurhaev-cargo/';
const b = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'], protocolTimeout: 120000 });
const errs = [];
const shot = async (p, name, sel) => {
  await p.evaluate(s => { const el = s ? document.querySelector(s) : null; if (el) window.scrollTo({ top: el.getBoundingClientRect().top + window.scrollY - 60, behavior: 'instant' }); else window.scrollTo({ top: 0, behavior: 'instant' }); }, sel);
  await new Promise(r => setTimeout(r, 700));
  await p.screenshot({ path: `screenshots/${name}.png` });
};
const d = await b.newPage();
d.on('pageerror', e => errs.push(e.message));
await d.setViewport({ width: 1440, height: 900 });
await d.goto(URL, { waitUntil: 'networkidle2' });
await d.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; });
await d.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 900));
await shot(d, 'desktop-1440', null);
for (const [sel, name] of [['#vezem', 'desktop-vezem'], ['#dokumenty', 'desktop-dokumenty'], ['#kuda', 'desktop-kuda'], ['#voprosy', 'desktop-voprosy'], ['#svyaz', 'desktop-svyaz']]) await shot(d, name, sel);
const pre = await d.evaluate(() => Math.round(document.querySelector('#holod').getBoundingClientRect().top + window.scrollY));
await d.evaluate(y => window.scrollTo({ top: y - 400, behavior: 'instant' }), pre);
await new Promise(r => setTimeout(r, 1300));
const st = await d.evaluate(() => Math.round(document.querySelector('.cold__stage').getBoundingClientRect().top + window.scrollY));
await d.evaluate(y => window.scrollTo({ top: y + 500, behavior: 'instant' }), st);
await new Promise(r => setTimeout(r, 800));
await d.screenshot({ path: 'screenshots/desktop-holod.png' });
const m = await b.newPage();
await m.setViewport({ width: 390, height: 844, deviceScaleFactor: 2 });
await m.goto(URL, { waitUntil: 'networkidle2' });
await m.evaluate(() => { document.documentElement.style.scrollBehavior = 'auto'; });
await m.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 900));
await shot(m, 'mobile-390', null);
for (const [sel, name] of [['#holod', 'mobile-390-holod'], ['#dokumenty', 'mobile-390-dokumenty'], ['#voprosy', 'mobile-390-voprosy']]) await shot(m, name, sel);
const o = await b.newPage();
await o.setViewport({ width: 1200, height: 630 });
await o.goto(URL, { waitUntil: 'networkidle2' });
await o.evaluate(() => document.fonts.ready);
await new Promise(r => setTimeout(r, 800));
await o.screenshot({ path: 'public/og.jpg', type: 'jpeg', quality: 86 });
console.log('done', errs);
await b.close();
